$tmp = 'D:\MineDeck-ux\tmp-build'; if (Test-Path $tmp) { Remove-Item $tmp -Recurse -Force }; New-Item -ItemType Directory -Force $tmp | Out-Null

# 1. a modpack a friend sent: Fabric 1.21.11, one mod from Modrinth, one file from a site MineDeck does not trust
$idx = [ordered]@{
  formatVersion = 1; game = 'minecraft'; versionId = '1.0.0'; name = '周末小整合'; summary = '朋友发来的小整合包'
  files = @(
    [ordered]@{ path = 'mods/lithium-fabric-0.21.4+mc1.21.11.jar'; hashes = [ordered]@{ sha1 = '203bdcb26e97b3217b045e1182651a7d7b6462ec'; sha512 = 'f14a5c3d2fad786347ca25083f902139694f618b7c103947f2fd067a7c5ee88a63e1ef8926f7d693ea79ed7d00f57317bae77ef9c2d630bf5ed01ac97a752b94' }; env = [ordered]@{ client = 'required'; server = 'required' }; downloads = @('https://cdn.modrinth.com/data/gvQqBUqZ/versions/Ow7wA0kG/lithium-fabric-0.21.4%2Bmc1.21.11.jar'); fileSize = 900462 },
