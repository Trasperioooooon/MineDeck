# 3. a single-player save (world generated by the seeded 26.3 server)
$src = Get-ChildItem 'D:\MineDeck-ux\return\servers' -Directory | Where-Object { (Get-Content (Join-Path $_.FullName 'instance.json') -Raw) -match '创造小镇' } | Select-Object -First 1
