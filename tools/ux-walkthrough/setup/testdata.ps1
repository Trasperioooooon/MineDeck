# 2. a server the user used to run by hand
$old = Join-Path $td '以前自己开的服'
New-Item -ItemType Directory -Force $old | Out-Null
Copy-Item 'D:\MineDeck-ux\return\cache\paper\paper-1.21.11-132.jar' (Join-Path $old 'paper-1.21.11-132.jar') -Force
